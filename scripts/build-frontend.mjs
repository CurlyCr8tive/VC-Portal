import { mkdirSync, rmSync, cpSync, copyFileSync, writeFileSync, readFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const dist = join(root, "dist");

const files = [
  "index.html",
  "login.html",
  "owner.html",
  "client.html",
  "set-up-account.html",
  "portal-styles.css",
  "styles.css",
];

function env(name, fallback = "") {
  return String(process.env[name] || fallback).trim();
}

function configValue(source, name, fallback = "") {
  const match = source.match(new RegExp(`${name}\\s*:\\s*["']([^"']*)["']`));
  return match?.[1] || fallback;
}

const localConfig = existsSync(join(root, "config.js")) ? readFileSync(join(root, "config.js"), "utf8") : "";

const config = {
  SUPABASE_URL: env("PUBLIC_SUPABASE_URL", configValue(localConfig, "SUPABASE_URL")),
  SUPABASE_ANON_KEY: env("PUBLIC_SUPABASE_ANON_KEY", configValue(localConfig, "SUPABASE_ANON_KEY")),
  APP_BASE_URL: env("PUBLIC_APP_BASE_URL", configValue(localConfig, "APP_BASE_URL", "")),
  OWNER_API_BASE_URL: env("PUBLIC_OWNER_API_BASE_URL", configValue(localConfig, "OWNER_API_BASE_URL")),
  CLIENT_API_BASE_URL: env("PUBLIC_CLIENT_API_BASE_URL", configValue(localConfig, "CLIENT_API_BASE_URL")),
};

rmSync(dist, { recursive: true, force: true });
mkdirSync(dist, { recursive: true });

for (const file of files) {
  copyFileSync(join(root, file), join(dist, file));
}

cpSync(join(root, "src"), join(dist, "src"), { recursive: true });

writeFileSync(
  join(dist, "config.js"),
  `// Generated by scripts/build-frontend.mjs. Browser-safe public runtime config only.\n` +
    `window.VC_PORTAL_CONFIG = ${JSON.stringify(config, null, 2)};\n`
);

console.log(`Built browser frontend in ${dist}`);
